//=====================================================================
// preload.v —— P5/A9「预装下一首」：**一套逻辑覆盖所有 N**（2026-10-10 v3）
//
// ★★★ 用户口径（2026-10-10 纠正 ✗→✓）：
//   「多首歌广义上包括一首歌，你要写多首歌的逻辑应该同样适用单首歌，
//     而不是在分情况讨论」
//   ⇒ 本模块**不判** N 的大小 ✗、**不判**"下一首是不是自己" ✗ ⇒ 一律照做 ✓
//
// 【槽与读取的总账（整套规则 ✓ 对任何 N 一样 ✓）】
//   四个物理槽；显示第 g 组（g=1,2,3）读物理槽 `(g-1+rot)&3` ✓
//   播放期：把**下一首的 g1**(BG1+CV1) 装进那个**当前没被显示**的槽 `(rot+3)&3` ✓
//   边界  ：`rot += 3` ✓ ⇒ 新首：g1→`(rot+3)&3`（刚装好的 ✓）、
//                              g2→`(rot+0)&3`、g3→`(rot+1)&3` ← ★ 这两个**必须补装** ✗
//   边界后：★ 本模块继续装 **g2、g3** ✓（此时那两个槽已被腾空、不再显示 ✓）
//   ★ 只预装 g1 而不补装 ✗ ⇒ 第 2/3 组读到**上一首**的数据 ✗，几何却按新首的
//     `g_bw[组]` ✗ ⇒ **尺寸不符 ⇒ 花屏** ✓（2026-10-10 板上实测 ✓）
//
// 【★ 为什么 g2/g3 要"边界后才装"】它们的目标槽 `(rot+0)/(rot+1)` 在边界前
//   **正被显示**（那是旧首的 g1/g2 ✓）⇒ 边界前写会**当场撕画面** ✗
//
// 【★★ v2 的两个坑（都已在 v3 修掉 ✓）】
//   坑 1 ✗：把"重新武装 `clr`"和"开始补装 `sw`"用了**同一个事件**（切歌那拍 ✓）
//     ⇒ 边界那拍 `st` 被清零 ⇒ **补装永远跑不起来** ✗
//     ⇒ 正解：**不需要 `clr`** ✓ —— 六笔做完**自动回到第 1 笔** ✓（= 为再下一首预装 ✓）
//   坑 2 ✗：边界后播放表会**重扫** ✓ ⇒ `nx_*` 会变成**再下一首**的 ✗
//     ⇒ 补装就会读到**错的人** ✗
//     ⇒ 正解：进入第 1 笔时把**六个索引拍快照** ✓，整轮六笔都用快照 ✓
//       （★ 槽基址**不**拍快照 ✗ —— 它必须用**当时**的 `rot` ✓，见下 ✓）
//
// 【六笔的顺序】BG1,CV1 →（等边界 `sw` ✓）→ BG2,CV2 → BG3,CV3 → 回到第 1 笔 ✓
//   每笔靠 `ld_done` 收尾 ✓；`start` 是**单拍脉冲** ✓
//   ★ 槽基址**每笔现取** ✓（顶层给的是**当时**的 `bg_base_f/cv_base_f` ✓
//     —— 它们含 `slot_rot` ✓ ⇒ 边界后自动指向新映射 ✓✓）
//
// 【开关】`en=0` ⇒ 一笔都不发 ⇒ 上层行为**逐位不变** ✓
//
// 目标器件：EG4S20BG256（HX4S20）· Verilog-2001 · `default_nettype none`
// 判据：`tb/tb_preload.v`（PR-01..PR-09）
//=====================================================================
`default_nettype none

module preload (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        en,          // ★ 开关（0 ⇒ 一笔都不发 ✓）
    input  wire        go,          // 允许起（顶层给：`lf_st == LF_DONE` ✓）
    input  wire        nx_vld,      // ★ 有地方可去（至少一首可播 ✓；**不是**"有下一首" ✗）
    // 下一首的六个文件表索引 ✓（进入第 1 笔时**拍快照** ✓）
    input  wire [7:0]  nx_bg1, input wire [7:0] nx_cv1,
    input  wire [7:0]  nx_bg2, input wire [7:0] nx_cv2,
    input  wire [7:0]  nx_bg3, input wire [7:0] nx_cv3,
    // 目标槽（顶层用**当时的** `bg_base_f/cv_base_f` 算好 ✓ —— 已含 `slot_rot` ✓）
    input  wire [20:0] s1_bg, input wire [20:0] s1_cv,   // g1 → 空槽 `(rot+3)&3` ✓ 播放期
    input  wire [20:0] s2_bg, input wire [20:0] s2_cv,   // g2 → `(rot'+0)&3` ✓ 边界后
    input  wire [20:0] s3_bg, input wire [20:0] s3_cv,   // g3 → `(rot'+1)&3` ✓ 边界后
    input  wire        sw,          // ★ 边界脉冲（切歌那拍 ✓）⇒ 放行 g2 阶段 ✓
    input  wire        ld_done,     // 装载器：本次完成（**单拍脉冲** ✓）
    input  wire [7:0]  ld_err,      // 装载器：错误码（done 那拍有效 ✓）
    output reg         act,         // ★ 所有权：1 = 本模块正在用 `ld_*` ✓
    output reg         start,       // 启动脉冲（单拍 ✓）
    output reg  [7:0]  idx,         // 文件表索引 ✓
    output reg  [20:0] slot,        // 目标槽基址 ✓
    output reg  [7:0]  err,         // 观测：最后一次的错误码 ✓
    output reg  [7:0]  n,           // ★ 瘦身：16 → 8 位 ✓（观测：累计发了几笔 ✓）
    output reg  [2:0]  st_out,      // 观测：当前步骤 0..5 ✓
    output wire        busy,        // ★ 六笔未走完（顶层用它**暂停轮播** ✗ 免得转到没装好的组 ✓）
    output reg         g1_ready,    // 下一首 BG1/CV1 的装载都已完成
    output reg         g1_bg_ok,
    output reg         g1_cv_ok
);
    reg  [2:0] st;                          // 0..5 = 六笔 ✓
    reg        sw_seen;                     // 边界来过（单拍脉冲 ✓ ⇒ 必须记住 ✓）
    reg        next_round_due;              // 物理备用槽轮转后，即使同一首也要重新预装

    // ---- ★ 六个索引的**快照**（进入第 1 笔时拍 ✓ v3 修坑 2 ✓）----
    reg [7:0] q_bg1, q_cv1, q_bg2, q_cv2, q_bg3, q_cv3;
    // ★★★ 2026-10-11 **硬门**：`l_*` = 「**上次真正装进 SDRAM 的那一组**」✓
    //   与 `q_*`（本轮**开始时**的快照 ✗）不同 —— `l_*` 只在**六笔全部完成**时才更新 ✓
    //   【为什么必须换】旧门拿 `nx_*` 与 `q_*` 比 ✗，而 `q_*` 每轮开始都刷新 ✗
    //     ⇒ 只要 `nx_*` 中途**抖一下**（切歌后播放表**重扫** ✓ 索引会瞬时变化 ✓）
    //       ⇒ 门**又开** ⇒ 一轮接一轮 ⇒ `pre_n` 一直涨 ✓（板上实证 99 ✓）
    //   【新门口径】只有「要装的」与「内存里已有的」**不同**才值得再跑 ✓
    reg [7:0] l_bg1, l_cv1, l_bg2, l_cv2, l_bg3, l_cv3;

    wire first = (st == 3'd0);
    // 第 1 笔要条件齐（开关 ＋ 开机收口 ＋ 有地方可去 ✓）；
    // 第 3 笔（g2 ✓）要**等边界** ✓；其余直接走 ✓
    // ★★★ 2026-10-11 板上抓出的**大 bug** ✗→✓（用户给回 `A9=7906323` ⇒ `pre_n=0x63=99` ✗）
    //   【症状】预装**在无限循环** ✗ —— 六笔做完自动回到第 1 笔 ✓（我 v3 的设计 ✓），
    //     而**单曲卡**上"下一首"**永远是它自己** ✗ ⇒ 它把**同样六张图反复装、一刻不停** ✗✗
    //   【后果】SDRAM 带宽被装载器**长期占满** ✗ ⇒ 图层取数被饿 ✓
    //     ⇒ ★ 字幕表**在内存里**（`lp_tab_ok=1` ✓）却取不出来 ⇒ **看不到字** ✓✓
    //       —— 板上实证：音频/频谱正常 ✓（优先级高 ✓）而字幕不出 ✓ 完全吻合 ✓
    //   【正解】只有"**下一首的素材和上一轮不同**"才值得再跑一轮 ✓
    //     · 单曲卡 ⇒ 六笔装完 ⇒ `nx_*` 与快照**逐位相同** ⇒ **不再重跑** ✓（带宽立刻让出来 ✓）
    //     · 多曲卡 ⇒ 换首后 `nx_*` 变了 ⇒ 自动跑新一轮 ✓（正是我们要的 ✓）
    //   ★ 六个索引**逐位比对**（几 LUT ✓）：q_* 是上一轮的快照 ✓
    wire nx_changed = (nx_bg1 !== l_bg1) || (nx_cv1 !== l_cv1) || (nx_bg2 !== l_bg2) ||
                      (nx_cv2 !== l_cv2) || (nx_bg3 !== l_bg3) || (nx_cv3 !== l_cv3);
    wire can_step = first          ? (en && go && nx_vld && (nx_changed || next_round_due)) :
                    (st == 3'd2)   ? sw_seen                            : 1'b1;

    // 本笔用哪个索引／哪个槽
    // ★★★ 2026-10-10 实测修正 ✗→✓（单元台 DIAG 抓到的 ✓）：
    //   第 1 笔必须用**实时输入 `nx_bg1`** ✗ —— 因为快照正是**那一拍**才拍的 ✓
    //   若第 1 笔也读快照 ⇒ 读到的是**上一轮的** `q_bg1`（初值 0 ✗）
    //     ⇒ 实测第 1 笔发出去的是 `idx=00` ✗（应为 `11` ✓）、
    //       新一轮的第 1 笔发的是 `11` ✗（应为 `77` ✓）—— 正是"**用了一轮旧的**" ✓
    //   ★ 而第 2~6 笔**必须**用快照 ✓ —— 边界后播放表会**重扫** ✗，
    //     实时值会变成"**再下一首**"的 ⇒ 装错人 ✗
    reg  [7:0]  sel_idx;
    reg  [20:0] sel_slot;
    always @(*) begin
        case (st)
        3'd0: begin sel_idx = nx_bg1; sel_slot = s1_bg; end          // ★ 实时 ✓（快照同拍拍下 ✓）
        3'd1: begin sel_idx = q_cv1;  sel_slot = s1_cv; end          // 以下都用快照 ✓
        3'd2: begin sel_idx = q_bg2;  sel_slot = s2_bg; end
        3'd3: begin sel_idx = q_cv2;  sel_slot = s2_cv; end
        3'd4: begin sel_idx = q_bg3;  sel_slot = s3_bg; end
        default: begin sel_idx = q_cv3; sel_slot = s3_cv; end
        endcase
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            st      <= 3'd0;
            sw_seen <= 1'b0;
            next_round_due <= 1'b0;
            act     <= 1'b0;
            start   <= 1'b0;
            idx     <= 8'd0;
            slot    <= 21'd0;
            err     <= 8'd0;
            n       <= 8'd0;
            q_bg1 <= 8'd0; q_cv1 <= 8'd0; q_bg2 <= 8'd0;
            q_cv2 <= 8'd0; q_bg3 <= 8'd0; q_cv3 <= 8'd0;
            // ★★ 2026-10-11 硬门寄存器**必须复位** ✗（今天已在 `tr1`/`fst_play`/`lrc_*` 上
            //   踩过三次"漏复位 ⇒ x ⇒ 比对恒假/恒真"✓）
            l_bg1 <= 8'd0; l_cv1 <= 8'd0; l_bg2 <= 8'd0;
            l_cv2 <= 8'd0; l_bg3 <= 8'd0; l_cv3 <= 8'd0;
            g1_ready <= 1'b0;
            g1_bg_ok <= 1'b0;
            g1_cv_ok <= 1'b0;
        end else begin
            start <= 1'b0;                          // ★ 单拍脉冲 ✓
            if (sw) begin
                sw_seen <= 1'b1;
                next_round_due <= 1'b1;
            end
            if (sw) g1_ready <= 1'b0;
            if (!act) begin
                if (can_step) begin
                    if (first) begin
                        g1_ready <= 1'b0;
                        g1_bg_ok <= 1'b0;
                        g1_cv_ok <= 1'b0;
                        next_round_due <= 1'b0;
                        // ★★ 拍快照：整轮六笔都用这一份 ✓（v3 修坑 2 ✓）
                        q_bg1 <= nx_bg1; q_cv1 <= nx_cv1;
                        q_bg2 <= nx_bg2; q_cv2 <= nx_cv2;
                        q_bg3 <= nx_bg3; q_cv3 <= nx_cv3;
                    end
                    idx   <= sel_idx;
                    slot  <= sel_slot;
                    start <= 1'b1;
                    act   <= 1'b1;
                    n     <= n + 8'd1;
                end
            end else if (ld_done) begin
                err <= ld_err;
                act <= 1'b0;                        // 交还一拍，下一拍按新 `st` 再发 ✓
                if (st == 3'd0) g1_bg_ok <= (ld_err == 8'd0);
                if (st == 3'd1) begin
                    g1_cv_ok <= (ld_err == 8'd0);
                    g1_ready <= 1'b1;
                end
                if (st == 3'd5) begin
                    // ★★★ 2026-10-11 **硬门** ✗→✓（用户第二次给出 `pre_n` 仍为 99 的证据 ✓）
                    //   【问题】原来"该不该起新一轮"是拿 `nx_*` 与**本轮开始时**的快照比 ✓
                    //     但每轮**开始时**都会刷新快照 ✗ ⇒ 只要 `nx_*` 中途**抖一下**
                    //     （切歌后播放表**重扫** ✓ 索引会瞬时变化 ✓）⇒ 门**又被打开** ✗
                    //     ⇒ 于是它**继续一轮接一轮** ⇒ `pre_n` 一直涨 ✓（板上 99 ✓）
                    //   【正解】改用"**上次真正装进去的那一组**"当基准 ✓：
                    //     `l_*` 只在**六笔全部完成**时才更新 ✓（= 记录 SDRAM 里现在到底是什么 ✓）
                    //     ⇒ 只有"要装的东西**和内存里已有的不同**"才值得再跑 ✓
                    //     ⇒ 抖一下不算 ✗（`nx_*` 抖回原值 ⇒ 与 `l_*` 仍相同 ⇒ 不起新一轮 ✓）
                    l_bg1 <= q_bg1; l_cv1 <= q_cv1;
                    l_bg2 <= q_bg2; l_cv2 <= q_cv2;
                    l_bg3 <= q_bg3; l_cv3 <= q_cv3;
                    st      <= 3'd0;
                    sw_seen <= 1'b0;
                end else begin
                    st <= st + 3'd1;
                end
            end
        end
    end

    // ★ `busy` = **正在补装 g2/g3**（顶层用它**暂停轮播** ✗）
    //   ★★★ 2026-10-11 板上第二次抓出 ✗→✓（用户："补装时感觉还在轮播，画面从上到下刷新成第二组"✗）
    //   【两个阶段必须区分开 ✗】
    //     阶段甲：预装 g1 完 ⇒ `st=2` ⇒ **停下来等边界**（可能等**一整首歌** ✗）
    //             ⇒ 这段**绝不能按住轮播** ✗（否则"轮播没了" ✓ —— 那是我 v2 的错 ✗）
    //     阶段乙：边界来了 ⇒ `sw_seen=1` ⇒ **真的在写 g2/g3 两个槽**（那两槽**正在被显示** ✗）
    //             ⇒ 这段**必须按住** ✗（否则转到正在写的槽 ⇒ 画面被"自上而下刷新" ✓ 板上实测 ✓）
    //   【我 v3 的错 ✗】写成 `act && (st>=2)` ✗ —— `act` 只在**发那一笔的几拍**为 1 ✗
    //     ⇒ 装载那几秒里 `act=0` ⇒ **busy=0** ⇒ 轮播照转 ⇒ 转到正在写的槽 ✓✓（用户实测 ✓）
    //   【正解】`(st >= 2) && sw_seen` ✓ —— 等边界时不按 ✓、真补装时按住 ✓
    //     （`sw_seen` 在边界那拍置 1 ✓、在本轮结束回到第 1 笔时清 0 ✓ ⇒ 天然分段 ✓）
    assign busy = (st >= 3'd2) && sw_seen;
    always @(*) st_out = st;
endmodule

`default_nettype wire
